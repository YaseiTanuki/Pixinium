import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

/** Embed repository assets before compilation; deployed Workers need no source filesystem. */
export function generateSiteAssets(root = fileURLToPath(new URL('../', import.meta.url))) {
  const directory = join(root, 'content/policies')
  const policies = Object.fromEntries(readdirSync(directory).filter(name => name.endsWith('.md')).sort()
    .map(name => [name.slice(0, -3), readFileSync(join(directory, name), 'utf8').replace(/\r\n/g, '\n')]))
  const icon = readFileSync(join(root, 'public/brand/pixinium-apple-icon.png')).toString('base64')
  const output = join(root, 'lib/generated/site-assets.ts')
  const source = '// Generated by scripts/generate-site-assets.mjs. Edit the Markdown/PNG sources instead.\n' +
    `export const POLICY_SOURCES = ${JSON.stringify(policies, null, 2)} as const\n\n` +
    `export const SHARE_IMAGE_ICON = ${JSON.stringify(`data:image/png;base64,${icon}`)}\n`
  mkdirSync(dirname(output), { recursive: true })
  if (!existsSync(output) || readFileSync(output, 'utf8') !== source) writeFileSync(output, source)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) generateSiteAssets()
